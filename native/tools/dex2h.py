#!/usr/bin/env python3
"""Turn classes.dex into a C header (kOverlayDex / kOverlayDexLen) that is compiled into the payload."""
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("// generated by tools/dex2h.py - do not edit\n#pragma once\n")
    f.write("static const unsigned char kOverlayDex[] = {\n")
    for i in range(0, len(data), 16):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\nstatic const unsigned kOverlayDexLen = %d;\n" % len(data))
